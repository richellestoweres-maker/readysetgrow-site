/**
 * Ready Set Grow: Homeschool Programs
 * ------------------------------------------------------------------
 * She asked for this and named the one she used herself, NEW College
 * Preparatory Academy, which taught her child through the middle and
 * high school years and which she rates highly. It is first in the
 * list, described warmly, and described accurately, which turned out
 * to matter.
 *
 * THE ACCREDITATION PART IS THE WHOLE POINT OF THE PAGE.
 * The word is used loosely by nearly everybody selling a curriculum,
 * and most parents have no way to tell a real accreditor from a logo.
 * So this leads with what accreditation actually is, what it actually
 * buys you, which is mostly transcripts and credit transfer, and the
 * fact that an unaccredited program is very often an excellent one.
 * A homeschool diploma written by a parent is accepted by most
 * colleges, and nobody should be frightened into paying for something
 * they do not need.
 *
 * WHERE WE COULD NOT CONFIRM SOMETHING, THE ENTRY SAYS SO. New College
 * Prep's own site presents a College Board CEEB code as accreditation.
 * A CEEB code is a school identification number for reporting test
 * scores, and the College Board does not accredit anybody. That is not
 * a mark against the school, and plenty of good schools describe
 * themselves loosely, but a parent choosing on the strength of
 * accreditation deserves to know to ask.
 *
 * MONEY. Every list like this is written for families who can pay
 * thousands. This one names a free public option, a free resource, and
 * the low cost ones, and it does not treat them as the lesser choice.
 */


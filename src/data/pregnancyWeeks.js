/**
 * Ready Set Grow: Week by week
 * ==================================================================
 * Weeks four through forty two. Each week carries four things and no
 * more, because a parent reads this on a phone in about twenty
 * seconds and a wall of text gets skipped.
 *
 *   size     a garden comparison, with the real measurement beside it
 *   baby     what is actually happening in there
 *   you      what she may feel, offered rather than predicted
 *   prepare  one thing, not a list
 *
 * ON THE SIZES
 * Every comparison has the real number next to it, because the fruit
 * on its own is charming and useless. Lengths are crown to rump until
 * about week twenty, which is how they are measured before the legs
 * uncurl, and crown to heel after that. The jump at week twenty is
 * real and is not the baby doubling overnight.
 *
 * ON THE "YOU" LINE
 * Written as may and some rather than will. A woman who has none of
 * the symptoms for her week should not close the app worried, and a
 * woman who has all of them should not feel unusual.
 *
 * ON THE PREPARE LINE
 * One thing. Never a checklist, never anything that costs money
 * unless it genuinely has to, and never anything that implies she is
 * behind.
 *
 * WHAT IS NOT IN HERE
 * Anything that reads as a warning. The warning signs are a separate
 * list that shows on every single week rather than appearing on the
 * week a complication is statistically likeliest, because a bleed at
 * twelve weeks matters just as much as one at thirty.
 *
 * Sizes and milestones checked September 2026 against ACOG, the NHS
 * week by week, and standard fetal biometry references.
 */


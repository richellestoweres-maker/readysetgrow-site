/**
 * Ready Set Grow: Sleep Foundations
 * ------------------------------------------------------------------
 * She asked for our version of what the big sleep accounts do, and the
 * difference is the whole point. They sell a method. This does not.
 *
 * WHAT IS ACTUALLY ON THIS PAGE
 * The setup, which is the part nobody charges for and the part that
 * does the most work. A dark room, a safe noise level, the right
 * layers, a repeatable order of cues, and a swaddle that is snug at
 * the chest and loose at the hips.
 *
 * THE 2 THINGS IT WILL NOT DO
 * 1. It will not say anything prevents SIDS, because nothing does.
 *    Safe sleep lowers risk, and that is the honest word for it.
 * 2. It will not tell a parent they have been doing it wrong. Every
 *    page that could land that way ends by saying so out loud, because
 *    a parent who reads this at 2am and closes it feeling awful is a
 *    page that did harm.
 *
 * Where an official number exists it is here with its source. Where one
 * does not, such as a room temperature range or a wake window, the page
 * says plainly that it is a rule of thumb rather than guidance.
 */



export function parentLearnById(id) {
  return PARENT_LEARN.filter((p) => p.id === id)[0] || null;
}

/* One a day, held still by the date so it does not change while she is
   halfway through reading it. */
export function parentLearnForDay(dayKey) {
  const s = String(dayKey || '');
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return PARENT_LEARN[h % PARENT_LEARN.length];
}

